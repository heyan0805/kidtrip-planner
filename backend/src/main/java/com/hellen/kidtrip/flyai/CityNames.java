package com.hellen.kidtrip.flyai;

import java.util.List;

/**
 * 城市名的守门 —— 挡掉"这压根不是一个具体城市"的值。
 *
 * ── 它为什么必须存在（2026-10-13 用户在界面上撞出来的）────────────────
 *   用户说"我想 11 月 17 日带孩子在**广东周边**游玩 6 天"，
 *   模型把「广东周边」**原样填进了 city**，于是整条链路变成：
 *     search-poi --city-name 广东周边 → 0 条 → 没有任何候选 → 行程排不出来。
 *
 *   要命的是它**不报错**。实测三个值：
 *     --city-name 广东周边 → { "data": null, "message": "empty",  "status": 0 }
 *     --city-name asdfgh   → { "data": null, "message": "empty",  "status": 0 }
 *     --city-name 珠海     → { "data": { "itemList": [ ...10 条 ] }, "status": 0 }
 *   「城市名是错的」和「这个地方真的没数据」在响应上**一模一样**（status 都是 0）。
 *   上游不会告诉我们参数错了，那就只能我们自己在下发之前挡。
 *
 * ── 它和 PoiCategories 是同一个机制换了张脸 ──────────────────────────
 *   那边是"模型不能自己造类别"，这边是"模型不能把区域说法当城市"。
 *   两次都是同一句话：**不是相信模型不会写错，而是让它写错了也没有用。**
 *
 * ⚠️ 为什么这里是**黑名单**，而类别那边是白名单：
 *   城市名有几万个，而且一直在变（撤县设市、改名），枚举不完；
 *   但"模型会把区域说法当成城市"这件事只有有限的几种写法，是可以枚举的。
 *   反过来去枚举"合法城市"会很危险：漏掉任何一个小城市，
 *   都会把一个**本来能查**的地方判成非法，用户被拦住还不知道为什么。
 *   误伤的代价（能查的查不了）比漏放的代价（白花一次查询）大，所以选黑名单。
 *
 * ⚠️ 省级名（"广东"）**故意不挡**：实测 `--city-name 广东` 是能返回 10 条的。
 *   我们不对"能不能查到"做多余假设 —— 挡的是我们已经确认查不到的写法。
 *   （但它对行程连贯性有影响，是另一个层面的问题，见 PoiCategories 无关，
 *     记在"广东周边 = 多城市行程"那条产品待办里。）
 */
public final class CityNames {

    /**
     * 区域 / 范围的说法。命中任何一个，就说明这不是一个城市，而是一片地方。
     *
     * "周边"是实测撞到的那一个（"广东周边"）；其余是同一家族的写法，一次挡掉 ——
     * 否则下次用户换个说法（"珠海附近""惠州一带""珠三角"），同样的坑要再踩一遍。
     */
    private static final List<String> REGION_MARKERS = List.of(
            "周边", "附近", "一带", "沿线", "地区", "周边游",
            "三角", "湾区", "城市群", "全省", "省内", "省市"
    );

    /**
     * "一个字符串里塞了好几个城市"的写法。
     *
     * 这几个字符不会出现在中文城市名内部，所以不会误伤。
     * 为什么要挡："珠海、广州"这种要么被上游静默查空（→ 又变成"没查到景点"），
     * 要么查出跨城的候选、被排成一份地理上不连贯的行程 —— 两种都不能接受。
     * 一个城市的行程只能有一个 city，含糊就是错。
     */
    private static final List<String> SEPARATORS = List.of("、", "，", ",", "/", "+", "＋");

    private CityNames() {
    }

    /**
     * 这个值能不能拿去查飞猪。
     *
     * 只判断"是不是一个单一的具体城市"，**不判断这个城市存不存在** ——
     * 存不存在只有上游知道，而它不告诉我们。这里的职责是挡掉我们自己能确认的错，
     * 不是假装能替上游做完整校验。
     */
    public static boolean isSingleCity(String raw) {
        if (raw == null || raw.isBlank()) {
            return false;
        }
        String city = raw.strip();
        for (String marker : REGION_MARKERS) {
            if (city.contains(marker)) {
                return false;
            }
        }
        for (String separator : SEPARATORS) {
            if (city.contains(separator)) {
                return false;
            }
        }
        return true;
    }

    /**
     * 拦住时给用户看的那句话。
     *
     * 它会通过 ApiResult 的 message **原样显示给用户**，所以必须是能照着做的话：
     * 说清"哪里不对"（不是一个具体城市）+ "该怎么办"（换成哪个词）。
     * 只说"城市不合法"等于什么都没说 —— 用户不知道合法的长什么样。
     */
    public static String hint() {
        return "请换成一个具体的城市名，比如「珠海」「广州」「深圳」——"
                + "飞猪只认具体的城市，「广东周边」这类区域说法查不到任何结果";
    }
}
