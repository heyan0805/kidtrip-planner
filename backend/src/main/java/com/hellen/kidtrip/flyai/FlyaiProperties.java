package com.hellen.kidtrip.flyai;

import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * 飞猪 CLI 的接入配置，对应 application.yaml 里的 kidtrip.flyai.*。
 *
 * 为什么把路径做成配置而不是写死在代码里：
 *   这些值全是"这台机器的事实"，不是"这个程序的事实"。
 *   换台电脑、换个 node、把 CLI 升级到别的位置，都不应该改 Java 代码。
 *
 * 为什么用 record + 紧凑构造器给默认值：
 *   配置文件里没写的键，绑定时会传 null / 0 进来；紧凑构造器正好是"在这里补默认值和校验"的地方。
 *   比在字段上写 @Value("${...:默认值}") 更集中，也更容易一眼看全"哪些是必填"。
 *
 * minGapMs 是 B3 加的：**实测上游有限流与风控**，密集串行会被拦。
 *   两个数字决定它：
 *     并发 6 个 → 3 个 429；连续串行 6 个不间隔 → 后 3 个 451（风控）。
 *     冷却 90 秒后，串行且间隔 7 秒的 4 次调用**全部成功**。
 *   所以"两次调用之间至少隔一会儿"不是优化，是**能不能用**的问题。
 */
@ConfigurationProperties(prefix = "kidtrip.flyai")
public record FlyaiProperties(
        String nodePath,
        String cliPath,
        int timeoutSeconds,
        /** 两次 CLI 调用之间的最小间隔（毫秒）。0 = 不间隔（只在测试里用） */
        long minGapMs,
        /** 同一组查询条件的结果缓存多久（秒）。避免同一个规划会话里重复花钱 */
        long cacheTtlSeconds,
        /**
         * 搜酒店时带上的星级筛选，形如 "4,5"。**空串 = 不筛**。
         *
         * 为什么要加这个 —— 一组实测（2026-10-13，深圳，带真实入离日期）：
         *   不带筛选：10 条里 **6 条是青旅/日租公寓**（舒坦时光青年公寓 ¥27、百联住宿公寓 ¥49、
         *             几米舍青年客栈 ¥44……），价格区间 ¥27~¥235。全是"经济型"。
         *   带 4,5  ：9 条里 **0 条**不适合亲子（皇冠假日、希尔顿花园、希亚途……），¥161 起。
         * 飞猪默认按**价格升序**返回，而价格升序在酒店这个品类里等于"把最差的排在最前面" ——
         * 对"带娃住哪儿"这个问题，默认排序给出的答案系统性地是错的。
         *
         * 顺带记两条**没生效**的参数，免得以后有人再试：
         *   `--hotel-types hotel`  —— 实测挡不住青旅（青旅在它眼里也算 hotel），返回还是 6/10 不合格；
         *   `--sort rate_desc`     —— 实测结果与默认几乎一致，且 `rate` 字段恒为 null（上游不下发评分）。
         */
        String hotelStars,
        /**
         * **一段城际交通的时长上限（分钟）** —— 这个项目唯一那条产品约束的落点。
         *
         * 默认 180（3 小时）—— 这是**产品决定**，不是技术限制。实测依据（2026-10-13，广州出发）：
         *   `--total-duration-hour 3` 之下这几条是真实存在的走法：
         *     广州→珠海 53 分 · 广州→汕头 87 分 · 珠海→深圳 104 分 · 深圳→汕头 102 分 · 汕头→厦门 84 分
         *   最长的一条是 104 分 —— 也就是说这条线画在 120 甚至 105 也**一条都不丢**。
         *   想更严就往下调（产品上完全站得住），想更松就往上调，都不用改代码。
         *
         * ⚠️ 上游的筛参数是**小时**（整数），所以这里会向上取整成小时再发
         *    （见 LegService.hoursCeiling）—— 也就是说这条线真正生效是在**本地**，
         *    上游那层只是粗筛。改这个数字不需要同步改任何别的地方。
         */
        int maxLegMinutes,
        /**
         * 预跑缓存的落盘路径。**空 = 不落盘**（纯内存，和加这个字段之前一模一样）。
         *
         * ── 它解决的是"现场"问题，不是"性能"问题 ────────────────────────
         *   纯内存缓存只在一次进程生命周期里有效。而现场演示最常见的动作就是**重启后端**，
         *   一重启，之前预热好的结果全没了 —— 偏偏那时候上游可能已经查不动了
         *   （实测：连续串行 6 个不间隔，后 3 个直接 451）。
         *
         *   配上这个路径之后，流程变成：
         *     提前一天 `--kidtrip.flyai.cache-file=... ` 跑一遍预跑 → 结果留在磁盘上
         *     演示当天用同样配置启动 → 那几趟车次**一次上游调用都不用发**
         *
         * ── 为什么默认留空，而不是给个默认路径 ────────────────────────────
         *   加一个组件不该让所有人的开发环境开始往磁盘上写文件。
         *   默认空 = 显式配置才启用 —— 想用它的人一定知道自己在准备什么。
         *
         * ⚠️ 配套注意：预跑结果的时效由 {@code cacheTtlSeconds} 管，而它的默认值只有 600 秒。
         *    预跑和演示之间隔了多久，就该把 TTL 调到比它更长，否则磁盘上的结果一到现场就全过期了。
         *    （不另设一个"落盘专用 TTL"是刻意的：那样就有两个时效概念，
         *      而"这条能不能用"只该有一个判据。）
         */
        String cacheFile
) {

    public FlyaiProperties {
        if (nodePath == null || nodePath.isBlank()) {
            nodePath = "node";
        }
        if (cliPath == null || cliPath.isBlank()) {
            // 没有默认值可以兜：这个路径完全取决于 CLI 装在哪。
            // 与其在运行到一半时给一句 "No such file or directory"，不如启动就失败。
            throw new IllegalStateException(
                    "缺少配置 kidtrip.flyai.cli-path —— 应指向 @fly-ai/flyai-cli 的 dist/flyai-bundle.cjs");
        }
        if (timeoutSeconds <= 0) {
            timeoutSeconds = 120;
        }
        if (minGapMs <= 0) {
            minGapMs = 3_000;
        }
        if (cacheTtlSeconds <= 0) {
            cacheTtlSeconds = 600;
        }
        // ⚠️ 这里必须区分**两种情况**，不能像上面几个字段那样一句 `== null || isBlank()` 了事：
        //    hotelStars 为 null → 配置文件里根本没写这个键 → 用默认值 "4,5"；
        //    hotelStars 为 ""   → 配置里**显式**写了空串 → 用户想关掉星级筛选 → 尊重它。
        //   如果把空串也当成"没配"，那"我想看看不带筛选是什么样"这件事就永远表达不出来 ——
        //   而这恰好是我们做实测时最需要的能力。
        //   （和规范化那层"把四种空统一成 null"是**相反**的取舍：那里统一是为了少判空，
        //    这里区分是因为两种空在语义上真的不同。判断依据永远是语义，不是形式。）
        if (hotelStars == null) {
            hotelStars = "4,5";
        } else {
            hotelStars = hotelStars.strip();
        }
        // 和上面的 hotelStars 相反，这里**没有"显式关掉"这种状态**：
        // "不限时长"不是一个合理的配置（那等于取消这个产品唯一的核心约束）。
        // 想放宽就把数字调大，而不是把它变成一个可以关掉的东西。
        if (maxLegMinutes <= 0) {
            maxLegMinutes = 180;
        }
    }
}
