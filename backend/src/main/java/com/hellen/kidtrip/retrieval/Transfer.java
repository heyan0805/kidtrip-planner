package com.hellen.kidtrip.retrieval;

/**
 * 一段**真实的**城际交通：从 `from` 到 `to`，坐哪一趟、几点发几点到、多久、多少钱。
 *
 * 为什么要有个东西（它解决的问题）：
 *   在这之前，行程里"怎么去"这一行**根本没有**，或者由模型编。
 *   而"带孩子不能长途"是这个项目唯一的身份约束 —— 一个约束如果没有任何真实数字支撑，
 *   它就只是一句宣传语。`durationMinutes` 就是那句话的落点。
 *
 * ── 它同时服务火车和飞机（2026-10-14 起）─────────────────────────
 *   `mode` 说这一段坐的是什么。**字段本身是载体无关的**，因为两种载体要回答的
 *   问题一模一样（几点走、几点到、多久、多少钱、能不能买），只有名称不同：
 *     serviceNo —— "高铁G270" / "深航ZH9501"
 *     seatClass —— "二等座"   / "经济舱"
 *     depStation—— "深圳北"   / "宝安"（机场短名，上游的 arrStationShortName 就是它）
 *   所以没有第二个类型。为飞机再写一个字段几乎一样的 record，
 *   只会让"哪些字段能信"的知识变成两份，然后两边慢慢走散。
 *
 * ── 两个字段为什么是日期时间而不是"08:36" ────────────────────────
 *   `depDateTime` / `arrDateTime` 是 ISO（"2026-11-17T08:36"），不是纯时刻。
 *   看着像冗余（哪一天不是已经在 TravelDay.day 里了吗），但**夜车会跨过午夜**：
 *   23:50 发、次日 00:40 到，只存 "23:50" / "00:40" 的话，前端会把它画成"提前到了"。
 *   这类"看不出来但确实错"的字段，正是 TravelDay 那边拒绝加 `nights` 的同一条标准 ——
 *   只不过那边的结论是"能算出来的不要存"，这边的结论是"**算不出来的必须存**"。
 *
 * ── 为什么 `direct` / `transferCity` 要显式存，而不是让前端去数 ────
 *   上游一条 journey 的 `segments` 在中转时是 N 段，到达站是**中转站**而不是目的地。
 *   把 first/last 的挑选规则放前端，等于把"哪些字段能信"的知识复制一份到另一门语言里。
 *   选好了再传下去，前端只负责显示。
 *
 * `priceYuan` 是**这一段的**价格，不是往返总价。
 *   飞猪的往返查询（`--back-date`）给的是一个合计价（实测 ¥140.00 = 单程 ¥70 × 2），
 *   拆不出来 —— 所以取单程查询，让每个数字都能对得上。
 *
 * ⚠️ 飞机的票价是**查询当时**的价格，浮动很大（实测同一条航线：11-17 深圳→上海
 *    ¥1510 起，12-10 只要 ¥610 起，2.5 倍）。所以任何用到它的地方都必须说清
 *    "这是查询时的参考价"，不能拿来当预算的确定数字。
 */
public record Transfer(
        /** 出发城市（画像里的 origin） */
        String from,
        /** 到达城市（画像里的 city） */
        String to,
        /**
         * 这一段坐什么走。**不参与任何判断**，只是把已定的事实带下去（见 TransportMode）
         */
        TransportMode mode,
        /** "广州南"（火车）/ "宝安"（机场短名）—— 上车/登机地点的短名 */
        String depStation,
        /** "珠海"（火车）/ "虹桥" —— 下车/落地地点的短名；中转时是**最终**到达地 */
        String arrStation,
        /** ISO 本地日期时间 "2026-11-17T08:36" —— 带日期，因为夜车会跨午夜 */
        String depDateTime,
        String arrDateTime,
        /**
         * 整段耗时（分钟）。中转时含候车，所以它 ≥ 各段 duration 之和。
         *
         * ⚠️ 对飞机来说这是**纯飞行时间**，不是门到门时间 —— 机场还要提前到、
         *    落地还要进城，两项加起来通常再多 2 小时左右。界面上的数字就是这一个，
         *    所以我们**不拿它和火车的时间直接比大小**（那是拿两种口径在对账）。
         */
        Integer durationMinutes,
        /** 这一段的票价（元）。取不到时为 null —— 不要填 0，"不知道"和"免费"不是一回事 */
        Double priceYuan,
        /**
         * 班次号，已把载体/航司的名字拼好："高铁G270" / "深航ZH9501"。
         *
         * 为什么叫 serviceNo 而不是 serviceNo（2026-10-14 改）：这个字段现在两种载体共用，
         * 再叫 serviceNo 就是一句会误导人的名字 —— 上游本来就是分开两个字段
         * （`marketingTransportName` + `marketingTransportNo`），单看编号也分不出
         * 高铁还是动车，所以才要拼；飞机同理（"ZH9501" 看不出是哪家航司）。
         */
        String serviceNo,
        /** "二等座" / "经济舱" */
        String seatClass,
        /** true = 一趟直达；false = 中途换乘（换乘站见 transferCity） */
        boolean direct,
        /** 换乘站名，直达时为 null。火车才有这个概念；航班走 --journey-type 1 时恒为 null */
        String transferCity,
        /** 飞猪的购票跳转链接 —— 演示时"点这里就能买"比任何文案都直接 */
        String jumpUrl
) {
}
