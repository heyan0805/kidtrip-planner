package com.hellen.kidtrip.rule;

/**
 * 被规则筛掉的一条，连同**原因**。
 *
 * 为什么宁可多写这个类型、也不 static void 地丢掉：
 *   筛掉这件事对用户是有信息的。他可能就想知道"为什么没有珠海长隆" ——
 *   答案可能是"票价 ¥362.88 超过你给的 300 预算"，这句话比"没找到合适的"有用一百倍。
 *   而且它对我们排障也值钱：候选少了，一看溯源就知道是"飞猪没给"还是"被规则杀了"，
 *   这两个原因的修法完全不同。
 */
public record Rejected(String name, String reason) {
}
