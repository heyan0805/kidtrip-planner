package com.hellen.kidtrip.plan;

import com.hellen.kidtrip.candidate.PoiCandidate;

/**
 * 一个**合格的、可以用来替换某个景点**的候选。
 *
 * ── 它为什么存在 ────────────────────────────────────────────────
 *   在这一轮之前，一份行程生成出来之后用户只能"看"或者"重新开始"。
 *   而家长真实的动作是："这个点孩子不感兴趣换一个""长隆三天都是它，换掉一天"。
 *   池子里本来就有几十个合格候选、实际只用掉十来个 ——
 *   那些剩下来的候选**一次上游调用都不花**就能用，只是以前没有把它们送出去。
 *
 * ── 它和 TravelSpot 的区别（不是"少几个字段"那么简单）────────────
 *   TravelSpot 是**已经排进日程的一个点**：它有时间、有模型写的 tips。
 *   SpotOption 是**还没决定要不要去的一个候选**：没有时间（几点去是排期的事），
 *   也没有 tips —— 因为 tips 是模型针对"某个点在某个行程里的位置"写的，
 *   一个还没被选中的候选没有这种东西。
 *
 *   ⚠️ 这个区别不是洁癖，它挡住一个具体的错：
 *      如果替换之后沿用原来那条 tips，用户会看到
 *      「广州动物园 ¥29.9 —— 长隆野生动物世界很大，建议先坐小火车再步行」。
 *      两句话各自都真实，拼在一起是**看不见的假话**。
 *      所以替换上来的点宁可没有 tips，也不能带着别人的 tips。
 *
 * ── 为什么带上 category ─────────────────────────────────────────
 *   因为用户换一个点的动机常常是"换个类型"（一天全是动物园、全是博物馆）。
 *   有了它，界面才能把"同类的"和"别的类型的"分开摆，
 *   而不是让用户在 28 个只有名字的选项里猜。它本来就躺在候选池里，白给的。
 *
 * ── 为什么 category 不放在 TravelSpot 上 ─────────────────────────
 *   前端排序时它才用得上，而排序发生在**用户换过之后**（那时每天的点已经变了），
 *   所以它必须留在池子里、由前端现算，不能固化进日程。
 *   一旦把 category 塞进 TravelSpot，就等于承认"这个点的类型是排期时定死的"——
 *   而它其实只是飞猪给这个商品的标签。
 */
public record SpotOption(
        String poiId,
        String name,
        /** 飞猪的商品标签（"动物园""博物馆""户外活动"）。可能为空串 —— 原始数据里就有空值 */
        String category,
        /** 门票（元）。null = 飞猪上没有可订的票，**不是免费**（和 TravelSpot 用的是同一条规矩） */
        Double priceYuan,
        /** 飞猪跳转短链。⚠️ 带追踪码，每次请求都会重新生成 */
        String bookUrl,
        String imageUrl,
        /** 纬度。**缺坐标时是 null 不是 0** —— 0 是几内亚湾，会把"附近"算成几千公里 */
        Double lat,
        Double lng
) {

    /** 从候选池里的一条景点做投影。**不加工任何字段** —— 界面要的就是飞猪的事实 */
    public static SpotOption from(PoiCandidate poi) {
        return new SpotOption(
                poi.poiId(),
                poi.name(),
                poi.category(),
                poi.priceYuan(),
                poi.bookUrl(),
                poi.imageUrl(),
                poi.lat(),
                poi.lng()
        );
    }
}
