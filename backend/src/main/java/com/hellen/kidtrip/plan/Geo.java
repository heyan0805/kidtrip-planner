package com.hellen.kidtrip.plan;

import java.util.Locale;

/**
 * 两点之间的直线距离（公里）—— 「近不近」这个判断的唯一来源。
 *
 * ── 这个类为什么直到现在才出现 ──────────────────────────────────
 *   在它之前，整个工程**没有任何一处算过距离**，但有两处注释都以为对方在算：
 *     · RuleChecker 写着「相邻景点距离不在这里 —— 那是排期阶段的活」
 *     · 前端 distanceKm 写着「精确判距离是后端 RuleChecker 的活」
 *   两句都成立，于是谁也没做。结果是模型排酒店时**看不到任何距离**，
 *   只能去读酒店名和截断到 22 个字的地址。
 *
 *   实测（2026-10-13，日志里的真实生成）：
 *     · 珠海 H2「长隆企鹅酒店」→ 海洋王国：模型写"紧邻"，真实 **0.33 公里** —— 对；
 *     · 桂林 H3「地球村雅致漓江酒店（…象鼻山店）」→ 象鼻山：模型写"步行可达"，
 *       真实 **0.70 公里** —— 也对。
 *   但这两次"对"，靠的是**酒店名字里恰好带着景区名**。第三次就没那么幸运了：
 *   同一次行程里它让用户第 1 天住桂林市区、第 2 天一早去阳朔，
 *   中间隔着 **42.4 公里**，而它全程不知道这件事。
 *
 *   **猜对不是能力，是运气；这个类是把运气换成算术。**
 *
 * ── 为什么用等距圆柱近似而不是 haversine ────────────────────────
 *   ① 精度够用。这次要分辨的是"几公里 vs 几十公里"，而两种算法在城市/城际尺度下
 *      差不到千分之一 —— 我们的阈值是 15 公里，千分之一是 15 米，
 *      对一个"要不要提醒用户"的决定毫无影响。追求高精度在这里是**没有收益的成本**。
 *   ② **一致性比精度重要。** 前端 `distanceKm()`（"换一个"候选清单的排序）用的就是
 *      这一套公式。后端若改用 haversine，同一对点会算出微小不同的值 —— 平时看不出来，
 *      但**在临界值附近会让两边排序不一致**：清单里排在第一位的那条候选，
 *      可能不是后端认为最近的那个。这种不一致不报错，只会在某一天突然冒出来。
 *      所以这里**刻意照抄前端那份**，连 6371 这个半径都一样。
 *      **改公式要同时改两边** —— 这是唯一的纪律。
 *
 * ── 为什么缺坐标返回 null 而不是 0 ──────────────────────────────
 *   "0 公里"的含义是"就在旁边"，而缺坐标的含义是"不知道"。
 *   把"不知道"写成 0，等于把一个未知的候选**排到最优先**：
 *   "换一个"清单会把它顶到第一行、酒店会显示成"紧邻景点"。
 *   契约里那条「0 是几内亚湾」讲的是同一件事。
 *   所以返回值是 `Double` 而不是 `double` —— **null 是要被调用方看见的**。
 */
public final class Geo {

    /** 前后端共用的地球半径。改它就要改两边（见类注释 ②）—— 前端同名常量在 TravelPlanner/index.tsx */
    private static final double EARTH_RADIUS_KM = 6371.0;

    private static final double DEG_TO_RAD = Math.PI / 180;

    private Geo() {
    }

    /**
     * 两点直线距离（公里）。**任一坐标缺失返回 null，不是 0。**
     *
     * ⚠️ 判缺必须用 `== null`，不能用"假值"式的判断。
     *    赤道上的点 latitude 就是 0，那是**真坐标**。前端那份实现里专门留了这条注释，
     *    因为 `if (a.lat && b.lat)` 这种写法看起来完全正常，只是会把赤道当成缺值 ——
     *    而"看起来正常的写法"正是这个工程反复踩的那类坑。
     */
    public static Double between(Double lat1, Double lng1, Double lat2, Double lng2) {
        if (!has(lat1, lng1) || !has(lat2, lng2)) {
            return null;
        }
        double dLat = (lat2 - lat1) * DEG_TO_RAD;
        // 经度方向要按纬度收缩：同样的经度差，在广州（23°N）对应的实际距离只有赤道的 92%
        double dLng = (lng2 - lng1) * DEG_TO_RAD * Math.cos(((lat1 + lat2) / 2) * DEG_TO_RAD);
        return EARTH_RADIUS_KM * Math.hypot(dLat, dLng);
    }

    /** 这个点有没有坐标。散在各处的 `lat != null && lng != null` 都该走这里 */
    public static boolean has(Double lat, Double lng) {
        return lat != null && lng != null;
    }

    /**
     * 给**模型**看的紧凑写法："0.7km" / "12.4km"；缺坐标 → "未知"。
     *
     * 为什么和下面 `kmText()` 不一样：**同一个数字，两种读者。**
     *   这一段要塞进 prompt，每家酒店后面挂着三个数字，再带上"约"和"公里"
     *   就纯粹是烧 token；而用户看的那份要多几个字才读得懂，那点开销完全值得。
     *
     * 用 Locale.ROOT 把小数点定死：默认 Locale 在某些地区会写成 "0,7"，
     * 而这串文字是要进 prompt 的 —— 一个逗号会让模型的解析变成什么，谁也说不准。
     */
    public static String label(Double km) {
        return km == null ? "未知" : String.format(Locale.ROOT, "%.1fkm", km);
    }

    /**
     * 给**用户**看的口语说法："约 42.4 公里"；不到 1 公里就说"不到 1 公里"。
     *
     * 为什么不到 1 公里要换个说法：写"0.3 公里"会让这个数字显得比它实际有的更可信
     * （它本来就是个近似值）。"不到 1 公里"既准确又够用 —— 这句话要回答的
     * 从来只是"能不能走过去"，而不是"走过去是 300 米还是 700 米"。
     *
     * ⚠️ 前端 `formatKm()`（"换一个"清单里那个）是同一套规则的另一份实现。
     *    两处都要改的话记得一起改 —— 同一句话在两个地方长得不一样，用户会以为
     *    它们说的是两件事。
     */
    public static String kmText(Double km) {
        if (km == null) {
            return "距离未知";
        }
        return km < 1 ? "不到 1 公里" : String.format(Locale.ROOT, "约 %.1f 公里", km);
    }
}
